function norm(value) {
  return String(value ?? '').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().trim();
}

function fnv1a(text) {
  let h = 0x811c9dc5;
  for (const ch of String(text)) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

function harmony(root) {
  const last = [...root].reverse().find(ch => VOWELS.includes(ch)) || 'i';
  return 'aou'.includes(last) ? 'A' : 'E';
}

function verbForm(root) {
  return root.slice(0,-1) + (harmony(root) === 'A' ? 'ur' : 'ir');
}

function candidateRoot(seed, attempt) {
  const h = (fnv1a(`${seed}:${attempt}`) + Math.imul(attempt + 1, 2654435761)) >>> 0;
  const c1 = CONS[h % CONS.length];
  const v1 = VOWELS[Math.floor(h / CONS.length) % VOWELS.length];
  const c2 = CONS[Math.floor(h / (CONS.length * VOWELS.length)) % CONS.length];
  const v2 = VOWELS[Math.floor(h / (CONS.length * VOWELS.length * CONS.length)) % VOWELS.length];
  if (c1 === c2) return candidateRoot(seed, attempt + 97);
  return `${c1}${v1}${c2}${v2}`;
}

function allocateNeo(pt, classe, usedNeo) {
  for (let attempt = 0; attempt < 50000; attempt++) {
    const root = candidateRoot(pt, attempt);
    const neo = classe === 'verbo' ? verbForm(root) : root;
    if (RESERVED.has(neo) || usedNeo.has(neo) || neo === norm(pt)) continue;
    return {root, neo};
  }
  throw new Error(`Não foi possível gerar forma Neo para ${pt}`);
}

function registerModernLexicon({registerEntry, makeEntry, core, targetAdditions = 500}) {
  const existingPt = new Set(core.PM.keys());
  const usedNeo = new Set([...core.NM.keys(), ...RESERVED]);
  const places = new Set();
  const entries = [];
  let added = 0;

  const addCanonical = spec => {
    const entry = makeEntry(spec.neo, spec.pt, spec.classe, spec.dominio, spec);
    const registered = registerEntry(entry);
    usedNeo.add(registered.neo);
    for (const alias of spec.aliases || []) core.PM.set(norm(alias), registered);
    if (spec.classe === 'verbo') {
      core.L2N[norm(spec.pt)] = registered.neo;
      core.N2L[registered.neo] = norm(spec.pt);
    }
    if (spec.isPlace) places.add(norm(spec.pt));
    entries.push(registered);
    return registered;
  };

  for (const spec of CURATED) addCanonical(spec);

  for (const spec of CONNECTIVES) {
    let neo = spec.neo;
    if ((usedNeo.has(neo) && core.NM.get(neo)?.pt !== spec.pt) || RESERVED.has(neo)) {
      neo = allocateNeo(`conj:${spec.pt}`, 'conjunção', usedNeo).neo;
    }
    const placeholder = `neofunc_${norm(spec.pt).replace(/[^a-z0-9]+/g,'_')}`;
    const entry = makeEntry(neo, spec.pt, spec.kind === 'relation' ? 'locução' : 'conjunção', 'Gramática/Conjunções', {
      aliases:[placeholder],
      base_pt:spec.pt,
      fonte_vocabulario:'Neo moderno — conectivos',
    });
    const registered = registerEntry(entry);
    core.PM.set(placeholder, registered);
    usedNeo.add(registered.neo);
    entries.push(registered);
  }

  for (const [pt, domain, classe] of REQUIRED_CONCEPTS) {
    const key = norm(pt);
    const isPlace = domain === 'Lugares/Geografia';
    if (core.PM.has(key)) {
      if (isPlace) places.add(key);
      continue;
    }
    const {root, neo} = allocateNeo(`required:${key}`, classe, usedNeo);
    const entry = makeEntry(neo, pt, classe, domain, {
      raiz:root,
      base_pt:pt,
      isPlace:isPlace || undefined,
      fonte_vocabulario:'Expansão moderna solicitada',
    });
    const registered = registerEntry(entry);
    existingPt.add(key);
    usedNeo.add(registered.neo);
    if (isPlace) places.add(key);
    if (classe === 'verbo') {
      core.L2N[key] = registered.neo;
      core.N2L[registered.neo] = key;
      core.VF[key] = {lemma:key, tense:null, inf:true};
    }
    entries.push(registered);
    added += 1;
  }

  const cursors = EXPANSION_GROUPS.map(() => 0);
  let progressed = true;
  while (added < targetAdditions && progressed) {
    progressed = false;
    for (let gi = 0; gi < EXPANSION_GROUPS.length && added < targetAdditions; gi++) {
      const group = EXPANSION_GROUPS[gi];
      while (cursors[gi] < group.words.length) {
        const pt = group.words[cursors[gi]++];
        const key = norm(pt);
        if (!key || existingPt.has(key) || core.PM.has(key)) {
          if (group.isPlace) places.add(key);
          continue;
        }
        const {root, neo} = allocateNeo(key, group.classe, usedNeo);
        const entry = makeEntry(neo, pt, group.classe, group.domain, {
          raiz:root,
          base_pt:pt,
          isPlace:group.isPlace || undefined,
          lemma_pt:group.classe === 'verbo' ? key : undefined,
          fonte_vocabulario:'Expansão moderna de frequência',
        });
        const registered = registerEntry(entry);
        existingPt.add(key);
        usedNeo.add(registered.neo);
        if (group.isPlace) places.add(key);
        if (group.classe === 'verbo') {
          core.L2N[key] = registered.neo;
          core.N2L[registered.neo] = key;
          core.VF[key] = {lemma:key, tense:null, inf:true};
        }
        entries.push(registered);
        added += 1;
        progressed = true;
        break;
      }
    }
  }

  if (added < targetAdditions) {
    throw new Error(`Expansão insuficiente: ${added}/${targetAdditions} novas bases`);
  }

  return {entries, places, added, connectives:CONNECTIVES};
}

